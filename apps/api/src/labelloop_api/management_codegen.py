"""Generate management and shared-session application contracts with unavailable adapters."""

import argparse
import json
from pathlib import Path

from fastapi import FastAPI

from .main import create_app
from .management import management_router, unavailable_operations


def contract_app() -> FastAPI:
    app = FastAPI(title="Labelloop management contract (unbound)", version="0.1.0")
    app.include_router(management_router())
    return app


def typescript_type(schema: dict) -> str:
    if not schema:
        return "unknown"
    if "$ref" in schema:
        return schema["$ref"].rsplit("/", 1)[1]
    if "const" in schema:
        return json.dumps(schema["const"])
    if "enum" in schema:
        return " | ".join(json.dumps(value) for value in schema["enum"])
    if "anyOf" in schema:
        # JSON Schema integers and numbers both map to TypeScript number.
        return " | ".join(dict.fromkeys(typescript_type(part) for part in schema["anyOf"]))
    kind = schema.get("type")
    if kind == "array":
        if "prefixItems" in schema:
            return "[" + ", ".join(typescript_type(part) for part in schema["prefixItems"]) + "]"
        return f"Array<{typescript_type(schema['items'])}>"
    if kind == "object":
        if "properties" not in schema:
            additional = schema.get("additionalProperties", {})
            if isinstance(additional, dict):
                value = typescript_type(additional)
            else:
                value = "unknown" if additional else "never"
            return f"Record<string, {value}>"
        required = schema.get("required", [])
        return (
            "{ "
            + "; ".join(
                f"{json.dumps(key)}{'' if key in required else '?'}: {typescript_type(value)}"
                for key, value in sorted(schema["properties"].items())
            )
            + " }"
        )
    if kind in {"integer", "number"}:
        return "number"
    if kind in {"string", "boolean", "null"}:
        return kind
    raise ValueError(f"unsupported schema type: {kind}")


def render_client(spec: dict) -> str:
    lines = [
        "// Generated by python -m labelloop_api.management_codegen; do not edit.",
        "// Unbound management contract: final session/queue integration is not asserted.",
        "",
    ]
    for name, schema in sorted(spec["components"]["schemas"].items()):
        lines.append(f"export type {name} = {typescript_type(schema)};")
    lines += [
        "",
        "export class ManagementApiError extends Error {",
        "  constructor(readonly status: number) {",
        "    super(`Management request failed (${status})`);",
        "  }",
        "}",
        "",
        "export class ManagementClient {",
        "  constructor(private readonly csrfToken: () => string) {}",
        "",
        "  private async request<T>(",
        "    path: string, method: string, body?: unknown, key?: string,",
        "  ): Promise<T> {",
        "    const headers: Record<string, string> = { Accept: 'application/json' };",
        "    if (method === 'POST') {",
        "      headers['Content-Type'] = 'application/json';",
        "      headers['X-CSRF-Token'] = this.csrfToken();",
        "      headers['Idempotency-Key'] = key ?? '';",
        "    }",
        "    const response = await fetch(`/api${path}`, {",
        "      method, headers, credentials: 'same-origin', cache: 'no-store', redirect: 'error',",
        "      body: body === undefined ? undefined : JSON.stringify(body),",
        "    });",
        "    if (!response.ok) throw new ManagementApiError(response.status);",
        "    return response.json() as Promise<T>;",
        "  }",
    ]
    for path, methods in sorted(spec["paths"].items()):
        for method, operation in sorted(methods.items()):
            inputs: list[str] = []
            expression = path
            query: list[str] = []
            for param in operation.get("parameters", []):
                name = param["name"]
                inputs.append(
                    f"{json.dumps(name)}{'' if param.get('required') else '?'}: "
                    f"{typescript_type(param['schema'])}"
                )
                if param["in"] == "path":
                    expression = expression.replace(
                        "{" + name + "}", "${encodeURIComponent(input[" + json.dumps(name) + "])}"
                    )
                if param["in"] == "query":
                    query.append(name)
            body = operation.get("requestBody")
            if body:
                inputs.append(
                    "body: " + typescript_type(body["content"]["application/json"]["schema"])
                )
            success = next(
                value for code, value in operation["responses"].items() if code.startswith("2")
            )
            result = typescript_type(success["content"]["application/json"]["schema"])
            lines += [
                "",
                f"  {operation['operationId']}(input: {{ {'; '.join(inputs)} }})"
                f": Promise<{result}> {{",
                f"    {'let' if query else 'const'} path = `{expression}`;",
            ]
            if query:
                lines.append("    const query = new URLSearchParams();")
                for name in query:
                    key = json.dumps(name)
                    lines.append(
                        f"    if (input[{key}] != null) query.set({key}, String(input[{key}]));"
                    )
                lines.append("    if (query.size) path += `?${query}`;")
            args = ["path", json.dumps(method.upper())]
            if body:
                args += ["input.body", 'input["idempotency-key"]']
            lines += [f"    return this.request<{result}>({', '.join(args)});", "  }"]
    lines += ["}", ""]
    return "\n".join(lines)


def rendered_contract() -> tuple[str, str]:
    spec = contract_app().openapi()
    return json.dumps(spec, indent=2, sort_keys=True) + "\n", render_client(spec)


def application_contract_app() -> FastAPI:
    """Use the real composition factory, without resolving auth, storage or operations."""
    return create_app(management_operations=unavailable_operations)


def rendered_application_contract() -> str:
    return json.dumps(application_contract_app().openapi(), indent=2, sort_keys=True) + "\n"


def generate(destination: Path) -> None:
    schema, client = rendered_contract()
    application_schema = rendered_application_contract()
    destination.mkdir(parents=True, exist_ok=True)
    (destination / "management.openapi.json").write_text(schema, encoding="utf-8")
    (destination / "management-client.ts").write_text(client, encoding="utf-8")
    (destination / "application.openapi.json").write_text(application_schema, encoding="utf-8")


def check_published(
    schema_path: Path, client_path: Path, application_schema_path: Path | None = None
) -> list[Path]:
    """Detect absent or stale tracked artifacts without rewriting them."""
    schema, client = rendered_contract()
    artifacts = [(schema_path, schema), (client_path, client)]
    if application_schema_path is not None:
        artifacts.append((application_schema_path, rendered_application_contract()))
    return [
        path
        for path, expected in artifacts
        if not path.is_file() or path.read_bytes() != expected.encode("utf-8")
    ]


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    mode = parser.add_mutually_exclusive_group(required=True)
    mode.add_argument("--output-dir", type=Path)
    mode.add_argument("--check", action="store_true")
    parser.add_argument(
        "--schema-path", type=Path, default=Path("apps/api/openapi/management.openapi.json")
    )
    parser.add_argument(
        "--client-path", type=Path, default=Path("apps/web/src/generated/management-client.ts")
    )
    parser.add_argument(
        "--application-schema-path",
        type=Path,
        default=Path("apps/api/openapi/application.openapi.json"),
    )
    args = parser.parse_args()
    if args.check:
        drift = check_published(args.schema_path, args.client_path, args.application_schema_path)
        if drift:
            parser.exit(1, "Management contract drift: " + ", ".join(map(str, drift)) + "\n")
    else:
        generate(args.output_dir)


if __name__ == "__main__":
    main()
